import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { buildInputs, simulate, type Level, type SimResult } from "../shared/sim.js";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");

const level = JSON.parse(readFileSync(resolve(root, "level/level.json"), "utf8")) as Level;

function toHex(bytes: Uint8Array): string {
  let s = "0x";
  for (const b of bytes) s += b.toString(16).padStart(2, "0");
  return s;
}

interface VectorSpec {
  name: string;
  length: number;
  jumps: number[];
}

const specs: VectorSpec[] = [
  { name: "clean", length: 200, jumps: [28, 78, 128, 160] },
  { name: "clean-alt", length: 200, jumps: [30, 80, 130, 162] },
  { name: "late-wall", length: 210, jumps: [28, 78, 128, 170] },
  { name: "max-length", length: 600, jumps: [28, 78, 128, 565] },
  { name: "died-spike-a", length: 200, jumps: [78, 128, 160] },
  { name: "short-no-goal", length: 150, jumps: [28, 78, 128] },
];

const vectors = specs.map((spec) => {
  const inputs = buildInputs(spec.length, spec.jumps);
  const result = simulate(level, inputs);
  return { spec, inputs, result };
});

for (const v of vectors) {
  const r = v.result;
  const detail =
    r.status === "goal"
      ? `time=${r.time}`
      : r.status === "died"
        ? `tick=${r.tick}`
        : r.status;
  console.log(`${v.spec.name.padEnd(16)} -> ${r.status} ${detail}`);
}

function expect(cond: boolean, msg: string): void {
  if (!cond) {
    console.error("VECTOR ASSERTION FAILED:", msg);
    process.exit(1);
  }
}

const byName = new Map<string, SimResult>(vectors.map((v) => [v.spec.name, v.result]));

const clean = byName.get("clean")!;
expect(clean.status === "goal" && clean.time === 200, "clean run must finish in 200 ticks");
const maxLen = byName.get("max-length")!;
expect(maxLen.status === "goal" && maxLen.time === 600, "max-length run must finish in 600 ticks");
const died = byName.get("died-spike-a")!;
expect(died.status === "died", "died-spike-a must die");
const short = byName.get("short-no-goal")!;
expect(short.status === "goalNotReached", "short-no-goal must not reach goal");
const late = byName.get("late-wall")!;
expect(late.status === "goal", "late-wall must reach goal");
expect(clean.status === "goal" && late.status === "goal" && late.time > clean.time, "late-wall must be slower");

const out = {
  level: "level.json",
  note: "Golden vectors generated by shared/sim.ts. Both the Foundry test and vitest replay these.",
  vectors: vectors.map((v) => {
    const r = v.result;
    return {
      name: v.spec.name,
      inputs: toHex(v.inputs),
      status: r.status,
      time: r.status === "goal" ? r.time : 0,
      tick: r.status === "died" ? r.tick : 0,
    };
  }),
};

writeFileSync(resolve(root, "level/vectors.json"), JSON.stringify(out, null, 2) + "\n");
console.log(`\nWrote ${out.vectors.length} vectors to level/vectors.json`);
